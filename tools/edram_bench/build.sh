#!/usr/bin/env bash
# Build the EDRAM sizing harness for arm64 Android. ~40s, no gradle.
#
# Deliberately does NOT go through premake/ndk-build: this is one translation
# unit and the point of the harness is a fast loop.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
NDK="${NDK:-$HOME/AppData/Local/Android/Sdk/ndk/25.0.8775105}"
TOOLS="$NDK/toolchains/llvm/prebuilt/windows-x86_64/bin"
GLSLC="$NDK/shader-tools/windows-x86_64/glslc.exe"
CXX="$TOOLS/aarch64-linux-android26-clang++.cmd"
[ -x "$GLSLC" ] || { echo "no glslc at $GLSLC"; exit 1; }

emit_header() {  # <spv> <symbol> <out.h>
  python - "$1" "$2" "$3" <<'PY'
import sys, struct
spv, sym, out = sys.argv[1], sys.argv[2], sys.argv[3]
d = open(spv, 'rb').read()
assert len(d) % 4 == 0, 'SPIR-V not word-aligned'
w = struct.unpack('<%dI' % (len(d) // 4), d)
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/edram_bench/build.sh - do not edit.\n')
    f.write('#pragma once\n#include <cstdint>\n')
    f.write('static const uint32_t %s[] = {\n' % sym)
    for i in range(0, len(w), 8):
        f.write('    ' + ' '.join('0x%08x,' % x for x in w[i:i+8]) + '\n')
    f.write('};\n')
print('  %s -> %s (%d words)' % (spv, out, len(w)))
PY
}

echo "[1/3] shaders"
"$GLSLC" -O -fshader-stage=vert "$HERE/shaders/fill.vert" -o "$HERE/shaders/fill.vert.spv"
"$GLSLC" -O -fshader-stage=frag "$HERE/shaders/fill.frag" -o "$HERE/shaders/fill.frag.spv"
emit_header "$HERE/shaders/fill.vert.spv" kFillVert "$HERE/shaders/fill_vert.h"
emit_header "$HERE/shaders/fill.frag.spv" kFillFrag "$HERE/shaders/fill_frag.h"

echo "[2/3] compile"
# -static-libstdc++: a bare adb-run binary has no libc++_shared.so on its
# loader path, so a dynamic link fails at exec with CANNOT LINK EXECUTABLE.
"$CXX" -std=c++17 -O2 -Wall -fno-exceptions -static-libstdc++ \
  -I"$HERE" \
  "$HERE/edram_bench.cc" -lvulkan -o "$HERE/edram_bench"

echo "[3/3] push"
# THE ONLY COMBINATION THAT WORKS, all three tried on 2026-08-13:
#   plain            -> destination rewritten to C:/Program Files/Git/data/...,
#                       adb prints "1 file pushed" and the file is NOT there
#   //data/...       -> remote path is literally //data/..., fchown fails
#   MSYS_NO_PATHCONV -> also stops SOURCE conversion; adb cannot stat /c/...
# So: disable conversion AND hand adb a Windows-form source.
SRC="$(cygpath -m "$HERE/edram_bench" 2>/dev/null || echo "$HERE/edram_bench")"
MSYS_NO_PATHCONV=1 adb push "$SRC" /data/local/tmp/edram_bench >/dev/null
# An adb shell ARGUMENT THAT STARTS WITH '/' is converted even inside quotes,
# so lead with cd. Same reason edram_ab.sh runs './edram_bench'.
adb shell "cd /data/local/tmp && chmod 755 edram_bench"
echo "ready: adb shell /data/local/tmp/edram_bench --help-less (see edram_ab.sh)"
