#!/usr/bin/env python3
"""Generate build/version.h from git.

WHY THIS EXISTS: build/version.h is #included by emulator_window.cc,
main_win.cc and trace_writer.cc, but NOTHING in this repo generated it and it
was never tracked in git. It had simply been created once, long ago, and
survived by never being deleted. That made build/ quietly non-reproducible:
`rm -rf build` (or any disk cleanup) broke the build with

    fatal error: 'build/version.h' file not found

and no script to recover it. Found on 2026-08-08 while reclaiming disk.

Idempotent and cheap: rewrites the header only when the content changes, so it
never triggers a needless rebuild of the three TUs that include it.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "build", "version.h")


def git(*args, default=""):
    try:
        return subprocess.check_output(
            ["git"] + list(args), cwd=ROOT, stderr=subprocess.DEVNULL
        ).decode("utf-8", "replace").strip()
    except Exception:
        return default


def main():
    commit = git("rev-parse", "HEAD", default="unknown")
    short = git("rev-parse", "--short", "HEAD", default="unknown")
    branch = git("rev-parse", "--abbrev-ref", "HEAD", default="unknown")
    # Committer date of HEAD, not "now" - so the header is a function of the
    # commit and does not churn on every invocation.
    date = git("show", "-s", "--format=%cs", "HEAD", default="1970-01-01")

    lines = [
        "// GENERATED by tools/build/gen_version_h.py - do not edit, do not commit.",
        "// Regenerate after cleaning build/:",
        "//   python tools/build/gen_version_h.py",
        "#ifndef GENERATED_XENIA_BUILD_VERSION_H_",
        "#define GENERATED_XENIA_BUILD_VERSION_H_",
        '#define XE_BUILD_BRANCH "%s"' % branch,
        '#define XE_BUILD_COMMIT "%s"' % commit,
        '#define XE_BUILD_COMMIT_SHORT "%s"' % short,
        '#define XE_BUILD_DATE "%s"' % date,
        "// XE_BUILD_IS_PR is deliberately NOT defined for local builds; the PR_*",
        "// macros below are only referenced inside #ifdef XE_BUILD_IS_PR.",
        "#endif  // GENERATED_XENIA_BUILD_VERSION_H_",
        "",
    ]
    text = "\n".join(lines)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if os.path.exists(OUT):
        with open(OUT, "r", encoding="utf-8") as f:
            if f.read() == text:
                print("build/version.h already current (%s@%s)" % (branch, short))
                return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote build/version.h (%s@%s %s)" % (branch, short, date))
    return 0


# The LLVM object cache directory is keyed on a stamp of the lowering sources.
# It was __DATE__ __TIME__ of llvm_assembler.cc, so any rebuild that recompiled
# that TU (a header change, a clean build) discarded every title's cache and
# cost a 7 to 11 minute cold compile per title (2026-09-20). A content hash of
# the lowering sources changes only when the lowering changes. Uncommitted
# edits count: the hash is of the working tree bytes.
# Only the files that hold the lowering. The memory manager, the cache wiring,
# and the backend header do not change generated code, so they are not keyed;
# an edit there keeps every title's cache (user, 2026-09-20).
LOWERING_SOURCES = [
    "src/xenia/cpu/backend/llvm/llvm_assembler.cc",
    "src/xenia/cpu/backend/llvm/llvm_assembler.h",
]
STAMP_OUT = os.path.join(ROOT, "build", "llvm_lowering_stamp.h")


def write_lowering_stamp():
    import hashlib
    h = hashlib.sha1()
    for rel in LOWERING_SOURCES:
        path = os.path.join(ROOT, rel)
        h.update(rel.encode("utf-8"))
        if os.path.exists(path):
            with open(path, "rb") as f:
                h.update(f.read())
    stamp = h.hexdigest()[:16]
    text = "\n".join([
        "// GENERATED by tools/build/gen_version_h.py - do not edit, do not commit.",
        "#ifndef GENERATED_XENIA_LLVM_LOWERING_STAMP_H_",
        "#define GENERATED_XENIA_LLVM_LOWERING_STAMP_H_",
        '#define XE_LLVM_LOWERING_STAMP "%s"' % stamp,
        "#endif",
        "",
    ])
    if os.path.exists(STAMP_OUT):
        with open(STAMP_OUT, "r", encoding="utf-8") as f:
            if f.read() == text:
                print("build/llvm_lowering_stamp.h already current (%s)" % stamp)
                return
    with open(STAMP_OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote build/llvm_lowering_stamp.h (%s)" % stamp)


if __name__ == "__main__":
    rc = main()
    write_lowering_stamp()
    sys.exit(rc)
